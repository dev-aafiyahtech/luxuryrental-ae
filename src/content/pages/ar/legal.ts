/** Working days, from a number (7) or a range in rules ("5 to 14"): "7 أيام عمل", "من 5 إلى 14 يوم عمل". */
function workingDays(spec: number | string): string {
  const [a, b] = String(spec).split(/\s*to\s*/).map(Number);
  const noun = (n: number) => (arPlural.select(n) === "few" ? "أيام عمل" : "يوم عمل");
  if (b !== undefined && !Number.isNaN(b)) return `من ${a} إلى ${b} ${noun(b)}`;
  const cat = arPlural.select(a);
  if (cat === "one") return "يوم عمل واحد";
  if (cat === "two") return "يومي عمل";
  return `${a} ${noun(a)}`;
}

/** A range in rules ("20 to 30") with its unit: "من 20 إلى 30 دقيقة". */
function rangeOf(spec: string, unit: "minute" | "day"): string {
  const [a, b] = spec.split(/\s*to\s*/).map(Number);
  return b === undefined || Number.isNaN(b) ? countText(a, unit, A) : `من ${a} إلى ${countText(b, unit, A)}`;
}

